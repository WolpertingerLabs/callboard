#!/usr/bin/env node
/**
 * The built-in Sandbox desktop profiles' recipe digests, pinned in source:
 * backend/src/services/sandbox-builtin-digests.generated.ts.
 *
 * A built-in is trusted (one-click build, no review) only when its file's
 * recipe hashes to the digest pinned here. The recipes' directory is plain
 * files in the install — user-writable in a source checkout or a user-level
 * npm install — so where a file is proves nothing; the pin, reviewed in git
 * like any other code, does.
 *
 *   node scripts/builtin-profile-digests.mjs           rewrite the map from the shipped recipes
 *   node scripts/builtin-profile-digests.mjs --check   fail (exit 1) if the map and the recipes disagree (the build runs this)
 *
 * The build checks rather than regenerates on purpose: regenerating would
 * pin whatever recipe sits in the directory at build time.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { parseProfileRecipe, profileRecipeDigest } = await import(join(root, "packages/computer-use/dist/index.js"));
const dir = join(root, "packages/computer-use/docker/profiles");
const target = join(root, "backend/src/services/sandbox-builtin-digests.generated.ts");

const digests = {};
for (const file of readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort()) {
  const recipe = parseProfileRecipe(readFileSync(join(dir, file), "utf8"));
  if (`${recipe.name}.json` !== file) throw new Error(`${file}: the file must be named ${recipe.name}.json`);
  digests[recipe.name] = profileRecipeDigest(recipe);
}
const text = `// Generated by scripts/builtin-profile-digests.mjs from packages/computer-use/docker/profiles/*.json. Do not edit:
// change a shipped recipe, then run \`node scripts/builtin-profile-digests.mjs\` and commit both.
/** Each shipped built-in profile's recipe digest (\`profileRecipeDigest\`). A built-in file not listed, or with another digest, is not trusted. */
export const BUILTIN_PROFILE_DIGESTS: Readonly<Record<string, string>> = Object.freeze({
${Object.entries(digests)
  .map(([name, digest]) => `  ${JSON.stringify(name)}: ${JSON.stringify(digest)},`)
  .join("\n")}
});
`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    /* missing: a mismatch */
  }
  // Compared as a map, not as text: a formatter may requote the keys.
  const pinned = Object.fromEntries([...current.matchAll(/^\s*"?([a-z0-9-]+)"?:\s*"([0-9a-f]{64})",?$/gm)].map((m) => [m[1], m[2]]));
  const same = (a, b) => JSON.stringify(Object.entries(a).sort()) === JSON.stringify(Object.entries(b).sort());
  if (!same(pinned, digests)) {
    console.error(
      "The pinned built-in profile digests (backend/src/services/sandbox-builtin-digests.generated.ts) do not match packages/computer-use/docker/profiles.\nIf you changed a shipped recipe on purpose, run `node scripts/builtin-profile-digests.mjs` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`Built-in profile digests match (${Object.keys(digests).join(", ")}).`);
} else {
  writeFileSync(target, text);
  console.log(`Wrote ${target}`);
}
